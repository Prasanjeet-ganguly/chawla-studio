/**
 * Loading-screen background pipeline for Chawla Studio.
 *
 * The cinematic preloader is built over one supplied photograph. That original
 * lives in /Loading Screen and is far too heavy to ship (a couple of megabytes
 * of PNG as the very first byte a visitor waits on), so this emits responsive
 * AVIF/WebP variants into /public/images/loading plus a typed manifest at
 * src/lib/loader-image.generated.ts.
 *
 * Replacing the loading screen's background is therefore: drop a new image into
 * /Loading Screen, delete the old one, and run `npm run loading-image`. Nothing
 * in the app names the file.
 *
 * With no source image at all the manifest still generates, with a null entry —
 * the loader then composes over its own ink gradient rather than a broken frame.
 *
 *   node scripts/optimize-loading-image.mjs            incremental
 *   node scripts/optimize-loading-image.mjs --force    rebuild
 */
import { existsSync } from 'node:fs';
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { buildVariants, readJson, slugify, toSrcSet } from './lib/raster.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE_DIR = path.join(ROOT, 'Loading Screen');
const OUT_DIR = path.join(ROOT, 'public', 'images', 'loading');
const MANIFEST = path.join(ROOT, 'src', 'lib', 'loader-image.generated.ts');
const CACHE_FILE = path.join(ROOT, '.loader-image-cache.json');

/**
 * Candidate widths for a full-bleed backdrop. Coarser than the photography
 * ladder because this frame is only ever seen behind type at `object-fit:
 * cover`, and every extra rung is weight on the critical path.
 */
const WIDTHS = [640, 1024, 1440, 1920, 2560];
const JPEG_FALLBACK_WIDTH = 1280;
const CACHE_VERSION = 'v1';

const FORCE = process.argv.includes('--force');

/**
 * The frame's mean colour, as a hex string.
 *
 * Painted under the photograph so the first frame of the loader is already the
 * right temperature — a warm ember rather than a black hole that then flashes
 * gold. Measured off the image, never chosen by hand.
 */
async function meanColour(file) {
  const { data } = await sharp(file, { failOn: 'none' })
    .rotate()
    .resize(1, 1, { fit: 'cover' })
    .removeAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const hex = [...data.subarray(0, 3)]
    .map((channel) => channel.toString(16).padStart(2, '0'))
    .join('');
  return `#${hex}`;
}

const MANIFEST_HEADER = `// AUTO-GENERATED by scripts/optimize-loading-image.mjs — do not edit by hand.
// Re-run \`npm run loading-image\` after replacing the file in /Loading Screen.

export type LoaderImage = {
  /** Slug derived from the original filename. */
  id: string;
  width: number;
  height: number;
  aspectRatio: number;
  /** Baseline JPEG, used as the <img src> fallback. */
  src: string;
  /** WebP responsive candidates. */
  srcSet: string;
  /** AVIF responsive candidates. */
  avifSrcSet?: string;
  /** Inline 20px blur, shown while the full frame decodes. */
  blurDataURL: string;
  /** The frame's mean colour, painted underneath it. */
  baseColor: string;
  /** Path to the untouched original, for provenance. */
  source: string;
};
`;

function renderManifest(entry) {
  if (!entry) {
    return `${MANIFEST_HEADER}
/**
 * No image was found in /Loading Screen when this manifest was generated, so the
 * loading screen composes over its own gradient instead of a photograph.
 */
export const LOADER_BACKGROUND: LoaderImage | null = null;
`;
  }

  const lines = [
    `  id: ${JSON.stringify(entry.id)},`,
    `  width: ${entry.width},`,
    `  height: ${entry.height},`,
    `  aspectRatio: ${entry.aspectRatio},`,
    `  src: ${JSON.stringify(entry.src)},`,
    `  srcSet: ${JSON.stringify(entry.srcSet)},`,
    entry.avifSrcSet ? `  avifSrcSet: ${JSON.stringify(entry.avifSrcSet)},` : null,
    `  blurDataURL: ${JSON.stringify(entry.blurDataURL)},`,
    `  baseColor: ${JSON.stringify(entry.baseColor)},`,
    `  source: ${JSON.stringify(entry.source)},`,
  ].filter(Boolean);

  return `${MANIFEST_HEADER}
export const LOADER_BACKGROUND: LoaderImage | null = {
${lines.join('\n')}
};
`;
}

async function main() {
  await mkdir(path.dirname(MANIFEST), { recursive: true });

  const files = existsSync(SOURCE_DIR)
    ? (await readdir(SOURCE_DIR)).filter((f) => /\.(jpe?g|png|tiff?|webp|avif)$/i.test(f)).sort()
    : [];

  if (files.length === 0) {
    console.warn(
      `[loading] no image in /Loading Screen — the loader will use its gradient only`
    );
    await writeFile(MANIFEST, renderManifest(null), 'utf8');
    await writeFile(CACHE_FILE, '{}', 'utf8');
    return;
  }

  if (files.length > 1) {
    console.warn(
      `[loading] /Loading Screen holds ${files.length} images; using "${files[0]}" — ` +
        'remove the others to pick a different one'
    );
  }

  const file = files[0];
  const abs = path.join(SOURCE_DIR, file);
  const info = await stat(abs);
  const key = [info.size, Math.round(info.mtimeMs), WIDTHS.join('-'), CACHE_VERSION].join(':');
  const cached = await readJson(FORCE ? '' : CACHE_FILE, {});

  if (cached.key === key && cached.entry && existsSync(MANIFEST)) {
    const present = existsSync(path.join(ROOT, 'public', cached.entry.src.replace(/^\/+/, '')));
    if (present) {
      console.log(`[loading] ${cached.entry.id} up to date`);
      return;
    }
  }

  await mkdir(OUT_DIR, { recursive: true });

  const id = slugify(file);
  const { width: sourceWidth } = await sharp(abs, { failOn: 'none' }).metadata();

  // Never upscale, but do keep the original's own width as the top rung when it
  // falls between two candidates — this frame is the one image on the site that
  // is always shown edge to edge.
  const widths = WIDTHS.filter((w) => w <= sourceWidth);
  if (widths.length === 0 || widths[widths.length - 1] < sourceWidth) widths.push(sourceWidth);

  const built = await buildVariants({
    file: abs,
    id,
    outDir: OUT_DIR,
    urlBase: '/images/loading',
    widths,
    avif: true,
    jpegWidth: JPEG_FALLBACK_WIDTH,
  });

  const entry = {
    id,
    width: built.width,
    height: built.height,
    aspectRatio: built.aspectRatio,
    src: built.src,
    srcSet: toSrcSet(built.webp),
    avifSrcSet: built.avif.length > 0 ? toSrcSet(built.avif) : undefined,
    blurDataURL: built.blurDataURL,
    baseColor: await meanColour(abs),
    source: `Loading Screen/${file}`,
  };

  await writeFile(MANIFEST, renderManifest(entry), 'utf8');
  await writeFile(CACHE_FILE, JSON.stringify({ key, entry }, null, 2), 'utf8');

  console.log(
    `[loading] ${entry.id} ${entry.width}x${entry.height} — ` +
      `${widths.length} widths, base ${entry.baseColor}`
  );
}

main().catch((error) => {
  console.error('[loading] failed:', error);
  process.exit(1);
});
